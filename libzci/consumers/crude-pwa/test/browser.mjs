// Real Chromium File + C callbacks + AudioContext/worklet integration.
// A fresh browser profile and dedicated origin never touch izci grants/state.
import { chromium } from 'playwright';
import { preview } from 'vite';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { mkdir, writeFile, readFile, copyFile } from 'node:fs/promises';
const root=fileURLToPath(new URL('../../../../',import.meta.url));
const consumer=path.join(root,'libzci/consumers/crude-pwa');
const server=await preview({root:consumer,preview:{port:5197,strictPort:true}});
const results=[];
let browser;
try {
  browser=await chromium.launch({headless:true,ignoreDefaultArgs:['--disable-background-timer-throttling','--disable-backgrounding-occluded-windows','--disable-renderer-backgrounding']});
  const context=await browser.newContext();
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',e=>{errors.push(String(e));console.error(e);});
  page.on('console',m=>{if(m.type()==='error')console.error(m.text());});
  await page.addInitScript(()=>{Object.defineProperty(globalThis,'AudioDecoder',{value:undefined,configurable:true});});
  await page.goto('http://localhost:5197');
  const snap=()=>page.evaluate(()=>window.libzci.snapshot());
  const command=(kind,value=0)=>page.evaluate(([k,v])=>window.libzci.command(k,v),[kind,value]);
  const wait=async predicate=>page.waitForFunction(predicate,undefined,{timeout:15000});
  await page.locator('#file').setInputFiles(path.join(root,'.local/libzci/media/r3/stereo.opus'));
  await page.locator('#open').click();
  await wait(()=>window.libzci.snapshot()?.snapshot.state==='Ready');
  console.log('opened',JSON.stringify(await snap()));
  await page.locator('#play').click();
  await wait(()=>window.libzci.snapshot()?.snapshot.position_frames>10000);
  const playing=await snap();
  assert(playing.output.energy>0,'real worklet output is audible/nonzero');
  assert(playing.snapshot.provider.version.includes('libopusfile-0.12'));
  await command('pause');
  await wait(()=>window.libzci.snapshot()?.snapshot.requested==='Held');
  const paused=(await snap()).snapshot.position_frames;
  await page.waitForTimeout(200);
  assert.equal((await snap()).snapshot.position_frames,paused);
  await command('seek',0.3);
  await wait(()=>!window.libzci.snapshot()?.snapshot.pending_operation && window.libzci.snapshot()?.snapshot.position_frames===14400);
  await command('play');
  await wait(()=>window.libzci.snapshot()?.snapshot.state==='Ended');
  const ended=await snap();assert.equal(ended.snapshot.position_frames,ended.snapshot.total_frames);
  results.push({test:'File reference output / pause / seek / final drain',result:'passed',playing,ended});
  await page.locator('#file').setInputFiles(path.join(root,'.local/libzci/media/r3/long.opus'));
  await page.locator('#open').click();
  await wait(()=>window.libzci.snapshot()?.snapshot.total_frames===1440006 && !window.libzci.snapshot()?.snapshot.pending_operation);
  await command('play');
  await wait(()=>window.libzci.snapshot()?.snapshot.position_frames>10000);
  const cdp=await browser.newBrowserCDPSession();
  const targets=await cdp.send('Target.getTargets');
  const decoder=targets.targetInfos.find(t=>t.type==='worker' && t.url.includes('decode-worker'));
  assert(decoder,'production decode worker is independently inspectable');
  const attached=await cdp.send('Target.attachToTarget',{targetId:decoder.targetId,flatten:false});
  let rpcId=0;
  const rpc=method=>cdp.send('Target.sendMessageToTarget',{sessionId:attached.sessionId,message:JSON.stringify({id:++rpcId,method})});
  await rpc('Debugger.enable');await rpc('Debugger.pause');
  await page.waitForTimeout(1400);
  const starving=await snap();
  await page.waitForTimeout(200);
  const starved=await snap();
  assert.equal(starved.snapshot.position_frames,starving.snapshot.position_frames,'underrun silence never advances media position');
  assert(starved.output.silence>starving.output.silence,'worklet supplies Pending silence');
  assert.equal(starved.snapshot.state,'Playing');assert.equal(starved.snapshot.decoding_eof,false);
  await rpc('Debugger.resume');
  await wait(()=>window.libzci.snapshot()?.snapshot.position_frames>100000);
  await cdp.detach();
  await page.evaluate(()=>window.libzci.suspend());
  await wait(()=>window.libzci.snapshot()?.snapshot.running==='Suspended');
  const suspended=(await snap()).snapshot.position_frames;
  await page.waitForTimeout(250);
  assert.equal((await snap()).snapshot.position_frames,suspended);
  await page.evaluate(()=>window.libzci.resume());
  await wait(()=>window.libzci.snapshot()?.snapshot.position_frames>20000);
  await command('mute',1);
  await wait(()=>window.libzci.snapshot()?.snapshot.mute && window.libzci.snapshot()?.output.intervalPeak===0);
  await command('mute',0);
  await command('volume',0.3);
  await wait(()=>window.libzci.snapshot()?.snapshot.volume<0.31 && window.libzci.snapshot()?.output.intervalPeak>0);
  // Seek while running, supersede multiple generations, then stop at origin.
  await command('seek',20);await command('seek',4);await command('seek',12.25);
  await wait(()=>!window.libzci.snapshot()?.snapshot.pending_operation && window.libzci.snapshot()?.snapshot.position_frames>=588000);
  assert((await snap()).snapshot.position_frames<650000,'no stale seek lands at 20 s');
  await command('stop');
  await wait(()=>!window.libzci.snapshot()?.snapshot.pending_operation && window.libzci.snapshot()?.snapshot.position_frames===0);
  await command('volume',1);
  await command('dispose');
  await wait(()=>window.libzci.snapshot()?.disposed===true);
  await page.locator('#open').click();
  await wait(()=>window.libzci.snapshot()?.snapshot.state==='Ready' && !window.libzci.snapshot()?.disposed);
  // Start at zero with a full paused pool. This is the long exact accounting run.
  await page.waitForTimeout(250);
  await command('play');
  await wait(()=>window.libzci.snapshot()?.snapshot.position_frames>5000);
  const beforeStall=await snap();
  await page.evaluate(()=>{const end=performance.now()+750;while(performance.now()<end) { /* stalled presentation */ }});
  await wait(()=>window.libzci.snapshot()?.snapshot.position_frames>30000);
  assert((await snap()).snapshot.position_frames>beforeStall.snapshot.position_frames+20000);
  const focus=await page.context().newCDPSession(page);
  await focus.send('Emulation.setFocusEmulationEnabled',{enabled:false});
  const other=await page.context().newPage();await other.goto('about:blank');await other.bringToFront();
  const visibility=await page.evaluate(()=>document.visibilityState);
  await page.waitForFunction(()=>window.libzci.snapshot()?.snapshot.state==='Ended',undefined,{timeout:45000});
  const long=await snap();
  assert.equal(long.snapshot.position_frames,1440006);
  assert.equal(long.output.media,1440006,'every long-source frame reached output once');
  assert.equal(long.stats.decodedFrames,1440006);
  assert(long.stats.maxRead<=32768);assert(long.output.highWater<=8);assert(long.stats.poolHighWater<=8);
  assert.equal(long.stats.codecHeapBytes,33554432);assert.equal(long.stats.poolBytes,262144);
  const reference=await readFile(path.join(root,'.local/libzci/media/r4/long.f32'));
  const samples=new Float32Array(reference.buffer,reference.byteOffset,reference.byteLength/4);
  let energy=0,peak=0;for(const sample of samples){energy+=sample*sample;peak=Math.max(peak,Math.abs(sample));}
  assert.equal(samples.length/2,long.output.media);
  console.log('long reference',JSON.stringify({outputEnergy:long.output.energy,energy,outputPeak:long.output.peak,peak}));
  assert(Math.abs(long.output.energy/energy-1)<1e-5,'browser output energy matches reference');
  assert(Math.abs(long.output.peak-peak)<1e-5,'browser peak matches reference');
  results.push({test:'long output / suspend / starvation / mute / rapid seek / UI stall',result:'passed',visibility,
    background:visibility==='hidden'?'passed':'not verified: headless Chromium kept the page visible',
    starvation:{starving,starved},long,reference:{frames:samples.length/2,energy,peak}});
  await other.close();
  // Full queue teardown and reopen must release resources, including C handles.
  await command('stop');
  await wait(()=>!window.libzci.snapshot()?.snapshot.pending_operation);
  await command('dispose');
  await wait(()=>window.libzci.snapshot()?.disposed===true);
  await page.locator('#file').setInputFiles(path.join(root,'.local/libzci/media/r3/mono.opus'));
  await page.locator('#open').click();
  await wait(()=>window.libzci.snapshot()?.snapshot.total_frames===12006 && !window.libzci.snapshot()?.disposed);
  await page.locator('#play').click();
  await wait(()=>window.libzci.snapshot()?.snapshot.state==='Ended');
  const mono=await snap();assert.equal(mono.output.media,12006);
  results.push({test:'dispose full output pool / new runtime / mono end trim',result:'passed',mono});
  await page.locator('#file').setInputFiles(path.join(root,'.local/libzci/media/r4/corrupt.opus'));
  await page.locator('#open').click();
  await wait(()=>window.libzci.snapshot()?.snapshot.state==='Failed');
  const corrupt=await snap();assert(/unsupported|corrupt|decoder failure/.test(corrupt.snapshot.error));
  const access=path.join(root,'.local/libzci/media/r4/access.opus');
  await copyFile(path.join(root,'.local/libzci/media/r3/long.opus'),access);
  await page.locator('#file').setInputFiles(access);await page.locator('#open').click();
  await wait(()=>window.libzci.snapshot()?.snapshot.state==='Ready' && window.libzci.snapshot()?.output.highWater===8);
  // Change only this test-owned file after Chromium captured its File snapshot.
  await writeFile(access,Buffer.alloc(536920));
  await command('play');
  await wait(()=>window.libzci.snapshot()?.snapshot.state==='Failed');
  const accessLost=await snap();assert(accessLost.snapshot.error.includes('unavailable'));
  results.push({test:'typed corrupt File failure / recover / live source access loss',result:'passed',corrupt,accessLost});
  const missing=await browser.newPage();
  await missing.route('**/opus-reference-*.wasm',route=>route.abort());
  await missing.goto('http://localhost:5197');
  await missing.locator('#file').setInputFiles(path.join(root,'.local/libzci/media/r3/mono.opus'));
  await missing.locator('#open').click();
  await missing.waitForFunction(()=>window.libzci.snapshot()?.snapshot.state==='Failed');
  results.push({test:'codec initialization failure resolves Loading with a typed error',result:'passed',snapshot:await missing.evaluate(()=>window.libzci.snapshot())});
  await missing.close();
  assert.equal(errors.length,0);
  console.log(results.map(r=>`${r.result}: ${r.test}`).join('\n'));
  await mkdir(path.join(root,'.local/libzci'),{recursive:true});
  await writeFile(path.join(root,'.local/libzci/r4-browser-evidence.json'),JSON.stringify(results,null,2));
} finally {await browser?.close();await new Promise(resolve=>server.httpServer.close(resolve));}
